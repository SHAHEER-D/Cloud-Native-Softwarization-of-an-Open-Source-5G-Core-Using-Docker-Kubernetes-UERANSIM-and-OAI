"""Generate the subscriber database: OAI schema + 101 UEs (IMSI 208950000000031-131).

All UEs share K/OPc (as in OAI's test database) and DNN "default". IMSIs ...031-...130 (UERANSIM)
use slice SST 222 / SD 00007B; IMSI ...131 (OAI NR-UE) uses SST 1 / SD 000001, because the OAI UE
only accepts SST 0-127 in its configuration.
Usage: python3 gen_db.py <oai_db2.sql from oai-cn5g-fed> <output.sql>
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
sql = open(src, encoding="utf-8").read()

# drop the stock subscriber rows; keep schema and all other tables
for table in ("AccessAndMobilitySubscriptionData", "AuthenticationSubscription",
              "SessionManagementSubscriptionData"):
    sql = re.sub(r"INSERT INTO `%s`.*?\);\n" % table, "", sql, flags=re.S)

K = "0C0A34601D4F07677303652C0462535B"
OPC = "63bfa50ee6523365ff14c1f45f88737d"
imsis = [f"2089500000000{n:02d}" if n < 100 else f"208950000000{n}" for n in range(31, 132)]
assert len(imsis) == 101 and all(len(i) == 15 for i in imsis)

auth = ",\n".join(
    f"('{i}', '5G_AKA', '{K}', '{K}', "
    "'{\\\"sqn\\\": \\\"000000000020\\\", \\\"sqnScheme\\\": \\\"NON_TIME_BASED\\\", \\\"lastIndexes\\\": {\\\"ausf\\\": 0}}', "
    f"'8000', 'milenage', '{OPC}', NULL, NULL, NULL, NULL, '{i}')" for i in imsis)
def slice_of(i):
    return (1, "000001") if i == "208950000000131" else (222, "00007B")


am = ",\n".join(
    f"('{i}', '20895', '{{\\\"defaultSingleNssais\\\": [{{\\\"sst\\\": {slice_of(i)[0]}, \\\"sd\\\": \\\"{slice_of(i)[1]}\\\"}}]}}')"
    for i in imsis)
dnn = ('{\\"default\\":{\\"pduSessionTypes\\":{\\"defaultSessionType\\": \\"IPV4\\"},'
       '\\"sscModes\\": {\\"defaultSscMode\\": \\"SSC_MODE_1\\"},'
       '\\"5gQosProfile\\": {\\"5qi\\": 9,\\"arp\\":{\\"priorityLevel\\": 7,\\"preemptCap\\": \\"NOT_PREEMPT\\",'
       '\\"preemptVuln\\":\\"PREEMPTABLE\\"},\\"priorityLevel\\":90},'
       '\\"sessionAmbr\\":{\\"uplink\\":\\"200Mbps\\", \\"downlink\\":\\"400Mbps\\"}}}')
sm = ",\n".join(
    f"('{i}', '20895', '{{\\\"sst\\\": {slice_of(i)[0]}, \\\"sd\\\": \\\"{slice_of(i)[1]}\\\"}}', '{dnn}')"
    for i in imsis)

sql += (
    "\n-- 101 test subscribers generated by tools/gen_db.py\n"
    "INSERT INTO `AuthenticationSubscription` (`ueid`, `authenticationMethod`, `encPermanentKey`, "
    "`protectionParameterId`, `sequenceNumber`, `authenticationManagementField`, `algorithmId`, `encOpcKey`, "
    "`encTopcKey`, `vectorGenerationInHss`, `n5gcAuthMethod`, `rgAuthenticationInd`, `supi`) VALUES\n" + auth + ";\n"
    "INSERT INTO `AccessAndMobilitySubscriptionData` (`ueid`, `servingPlmnid`, `nssai`) VALUES\n" + am + ";\n"
    "INSERT INTO `SessionManagementSubscriptionData` (`ueid`, `servingPlmnid`, `singleNssai`, "
    "`dnnConfigurations`) VALUES\n" + sm + ";\n"
)
open(dst, "w", encoding="utf-8").write(sql)
print(f"wrote {dst}: {len(imsis)} subscribers")
